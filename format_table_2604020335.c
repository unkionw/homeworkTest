#include <stdio.h>

/*
 * 说明：printf 的宽度（如 %-12s）按“字节”计算，一个汉字占 3 字节
 * 却只显示 2 列，所以含中文的列直接用 %-12s 会错位，
 * 这里按显示列数手工补齐。列宽：编号 6 | 名称 12 | 单价 10
 */

int main()
{
    // 表头
    printf("%s %s %s\n", "  编号", "名称        ", "      单价");

    // 4 行商品数据：编号用 %6d，单价用 %10.2f，保留两位小数
    printf("%6d %s %10.2f\n", 1, "铅笔        ", 1.50);
    printf("%6d %s %10.2f\n", 2, "笔记本      ", 5.80);
    printf("%6d %s %10.2f\n", 3, "橡皮        ", 0.75);
    printf("%6d %s %10.2f\n", 4, "圆规        ", 12.00);

    return 0;
}
