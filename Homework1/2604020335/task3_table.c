#include <stdio.h>

int main()
{
    /* 三个控制符：%6d 编号右对齐占 6 列，%-12s 名称左对齐占 12 列，
       %10.2f 单价占 10 列、保留两位小数。
       注意：printf 的宽度按字节算，一个汉字占 3 字节却只显示 2 列，
       所以商品名统一用两个字，%-12s 补出的空格数才相同，三列才对得齐。 */
    printf("%6s %-12s %10s\n", "  编号", "名称", "      单价");
    printf("%6d %-12s %10.2f\n", 1, "铅笔", 1.50);
    printf("%6d %-12s %10.2f\n", 2, "橡皮", 5.80);
    printf("%6d %-12s %10.2f\n", 3, "直尺", 0.75);
    printf("%6d %-12s %10.2f\n", 4, "圆规", 12.00);

    return 0;
}
